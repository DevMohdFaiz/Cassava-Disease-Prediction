device = "cuda" if torch.cuda.is_available() else "cpu"
model, clip_preprocess = clip.load("ViT-B/32", device=device)
base_embeddings= np.load("models/img_emb_2025-12-10_17-43.npy")
data_dir = Path('datasets/train/train')
data_classes = ['cbb', 'cbsd', 'cgm', 'cmd', 'healthy']

class OOD:
    """Out of Distrubution (OOD) Detector for Cassava Disease Model"""
    def __init__(self, model, clip_preprocess, base_embeddings, device, data_dir, data_classes):
        """
        OOD class Instantiator

        Args:      
            model: CLIP Model
            clip_preprocess: Image Preprocessor for CLIP 
            base_embeddings: Image Embeddings generated by CLIP
            device: device 
            param data_dir: Dircetory of the data file
            param data_classes: Data Classes
        """
        self.model = model
        self.clip_preprocess = clip_preprocess
        self.base_embeddings = base_embeddings
        self.device = device
        self.data_dir = data_dir
        self.data_classes = data_classes

    def plot_dir_contents(self):
        data_dir_dict = pd.Series({})
        for dir in [d for d in self.data_dir.iterdir()]:
            data_dir_dict[Path(dir).stem] = len([d for d in dir.iterdir()])
        data_dir_dict.plot(kind='barh')
        plt.title(f"Contents of {data_dir}")
        return data_dir_dict


    def get_random_images(self, num_images:int=10, equal_per_class=False, num_images_per_class=None):
        """Get random images"""
        random_images = []
        if not equal_per_class:
            for _ in range(num_images):
                random_class = self.data_dir/random.choice(self.data_classes)
                random_img = random.choice([d for d in random_class.iterdir()])
                random_images.append(random_img)
        else:
            for img_class in self.data_classes:
                random_imgs = random.sample([d for d in (self.data_dir/img_class).iterdir()], num_images_per_class)
                random_images.append(random_imgs)

        return random_images


    def plot_random_images(self, num_images:int=15, nrow:int=5):
        """Plot random images"""
        _, ax = plt.subplots(figsize=(10, 8))    
        random_images_tensor = []
        for random_img in self.get_random_images(num_images=num_images):        
            image_tensor = read_image(random_img)
            resize_transform = transforms.Resize((228,228))
            resized_img = resize_transform(image_tensor)
            random_images_tensor.append(resized_img)

        img_grid =make_grid(random_images_tensor, nrow=nrow, padding=2)
        image = to_pil_image(img_grid)
        ax.imshow(image)
        plt.axis('off')
        ax.set_title(f"Random cassava images")
        return random_images_tensor


    def create_equal_dir(self, equal_images):
        dataset_dir = Path.cwd()/"datasets"
        equal_classes_dir = dataset_dir/"equal_classes"
        if equal_classes_dir.exists():
            shutil.rmtree(equal_classes_dir)
        equal_classes_dir.mkdir(exist_ok=True)

        for dir in equal_images:
            current_class = dir[0].parent.stem
            current_dir = equal_classes_dir/current_class
            current_dir.mkdir(exist_ok=True)
            for d in dir:
                shutil.copy2(d, current_dir)
        return equal_classes_dir


    def get_image_embedding(self, img_path):
        """Get image embeddings using CLIP"""
        try:
            img = self.clip_preprocess(Image.open(img_path)).unsqueeze(dim=0).to(self.device)
        except:
            img = self.clip_preprocess(img_path).unsqueeze(dim=0).to(self.device)
        with torch.no_grad():
            emb = self.model.encode_image(img)
        emb = emb/ emb.norm(dim=-1, keepdim=True)
        return emb.cpu().numpy().flatten()


    def get_all_image_embeddings(self, all_images):
        """Get embeddings for all images in a directory"""
        imgs_embeds = []
        for imgs, cls in tqdm(zip(all_images, self.data_classes)):
            # img_emb= []
            for img in tqdm(imgs):
                if cls in img.stem:
                    image_emb = self.get_image_embedding(img_path=img)
                    imgs_embeds.append(image_emb)
                    # img_labels.append(cls)
        centroid = np.mean(imgs_embeds, axis=0)
        return imgs_embeds, centroid


    def get_ood_score(self, test_img_embedding, method="relative_mahalanobis"):
        """Get OOD score for a single image"""
        if method=="max_cosine": 
            ood_score = self.base_embeddings @ test_img_embedding 
            return ood_score.max()
        elif method == "knn":
            k = min(5, len(self.base_embeddings))
            ood_score = test_img_embedding @ self.base_embeddings
            top_scores = np.partition(ood_score, -k)[-k:]
            return top_scores.mean()
        elif method == "relative_mahalanobis":
            ood_score = np.linalg.norm(self.base_embeddings - test_img_embedding, axis=1)
            return ood_score.min()
    

    def analyze_img(self, image: Union[Image.Image, Path]):
        """
        Analyze an uploaded image and give an Out of Distribution (OOD) Score
        Args:
            image: Image | Path
        Returns:
            ood_score, origianl image, transformed_image 
        """
        # if isinstance(image, Path):
        #     img = Image.open(image)
        # elif isinstance(image, Image.Image):
        #     img = image
        # else:
        #     raise Exception("image must be an image path or an image")
        try:
            img = Image.open(image)
        except:
            img = image 
        image_emb = self.get_image_embedding(img_path=img)
        ood_score = self.get_ood_score(test_img_embedding=image_emb, method="relative_mahalanobis")
        return ood_score, img, to_pil_image(clip_preprocess(img))


    def plot_random_images_with_ood(self, num_images):
        """Plot randonmly generated images for visualization"""
        random_images = self.get_random_images(num_images=num_images)
        nrows = 3
        ncols = int(np.ceil(len(random_images)/nrows))
        fig, ax = plt.subplots(figsize=(10, 7), nrows=nrows, ncols=ncols)
        ax=ax.flatten()
        for idx, img in enumerate(random_images):
            img = Image.open(img)
            ood_score, _, _ = self.analyze_img(img)
            ax[idx].imshow(img)
            ax[idx].set_title(f"OOD: {ood_score:.3f}")
            ax[idx].axis('off')

        for j in range(idx+1, len(ax)):
            fig.delaxes(ax[j])